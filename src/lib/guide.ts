/** Which instructions a role sees in its cabinet. */
export const guideFor = (role: string) =>
  role === "admin"
    ? OWNER_GUIDE
    : role === "operator" || role === "manager"
      ? ADMIN_GUIDE
      : TEACHER_GUIDE;

/** The same text as Markdown, for sending by messenger or printing. */
export function guideMarkdown(g: Guide) {
  return [
    `# ${g.title}`,
    `_${g.who}_`,
    "",
    ...g.intro,
    "",
    ...g.sections.flatMap((s) => [
      `## ${s.title}`,
      ...s.steps.map((x) =>
        x.startsWith("!") ? `> **Важно:** ${x.slice(1)}` : `- ${x}`,
      ),
      "",
    ]),
  ].join("\n");
}
